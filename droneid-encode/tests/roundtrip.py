#!/usr/bin/env python3
"""Generate and CRC-validate a synthetic packet at both supported rates."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ENCODER = ROOT / "droneid_encode.py"
VALIDATOR = ROOT / "validate_with_decoder.py"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--locate-lib", type=Path,
                        default=Path(__file__).resolve().parents[2] /
                        "scan2400/build/droneid-native/src/locate/libdroneid_locate.so")
    args = parser.parse_args()

    # Minimal 89-byte DUML-shaped body. CRC is generated by the encoder.
    body = bytearray(89)
    body[:3] = bytes((0x58, 0x10, 0x02))
    payload_hex = body.hex()
    with tempfile.TemporaryDirectory(prefix="droneid-encode-") as temp:
        temp_path = Path(temp)
        for rate in (15_360_000, 30_720_000):
            iq_path = temp_path / f"waveform-{rate}.cf32"
            generated = subprocess.run(
                [sys.executable, str(ENCODER), "--payload-hex", payload_hex,
                 "--rate", str(rate), "--output", str(iq_path)],
                check=True, capture_output=True, text=True)
            metadata = json.loads(generated.stdout)
            decoded = subprocess.run(
                [sys.executable, str(VALIDATOR), str(iq_path), "--rate", str(rate),
                 "--locate-lib", str(args.locate_lib)],
                check=True, capture_output=True, text=True)
            result = json.loads(decoded.stdout)
            if not result["crc_valid"]:
                raise SystemExit(f"CRC validation failed at {rate} samples/s")
            print(f"PASS {rate}: {metadata['sample_count']} samples, "
                  f"decoded sequence {result['sequence_number']}, CRC valid")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
